def main():
    src = open(f'{KA}/app.js', encoding='utf-8').read()
    for a, b in REPLACEMENTS:
        src = src.replace(a, b)
    # заменяем содержимое раздела «Источники»
    start = src.find('      <h2>Словарь</h2>')
    end = src.find('    </div>\n  </div>`);', start)
    if start != -1 and end != -1:
        src = src[:start] + SOURCES_RO + '\n' + src[end:]
    open(f'{RO}/app.js', 'w', encoding='utf-8').write(src)

    for f in ['style.css', 'sw.js']:
        text = open(f'{KA}/{f}', encoding='utf-8').read()
        if f == 'sw.js':
            text = (text.replace('kartuli-shell', 'romana-shell').replace('kartuli-audio', 'romana-audio')
                        .replace("'data/words.json'", "'data/words-ro.json'")
                        .replace("'data/alphabet.json'", "'data/alphabet-ro.json'")
                        .replace("'data/mnemonics.json'", "'data/mnemonics-ro.json'"))
        open(f'{RO}/{f}', 'w', encoding='utf-8').write(text)
    print('код перенесён из грузинского проекта')


if __name__ == '__main__':
    main()
