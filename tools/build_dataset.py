# репрессии в словарь не идут: из новостных корпусов они лезут сами собой.
HEAVY = re.compile('|'.join([
    r'наркотик', r'наркоман', r'героин', r'кокаин', r'марихуан', r'конопл', r'гашиш',
    r'опиум', r'морфин', r'амфетамин', r'каннабис', r'метадон',
    r'фашиз', r'фашист', r'нациз', r'нацист', r'национализм', r'националист', r'расиз',
    r'расист', r'шовиниз', r'экстремиз', r'антисемит', r'ксенофоб', r'апартеид', r'геноцид',
    r'холокост', r'сегрегац', r'дискриминац', r'террор', r'теракт', r'диктатур',
    r'тоталитар', r'репресс', r'концлагер', r'цензур', r'пропаганд',
]), re.I)

# пометы, по которым значение целиком не берём в учебный словарь
OFFENSIVE = re.compile(r'^(вульг|груб|бран|обсц|неценз|мат\b|презр|уничиж|пренебр|оскорб|неодобр|табу)')
SLANG = re.compile(r'^(жарг|сленг|арго|прост\b|разг\.-сниж)')


def strip_labels(g):
    """убрать пометы вида 'полит.' в начале"""
    return re.sub(r'^((?:[а-яё]{2,10}\.\s*)+)', '', g).strip()

# ---------- 1. ручное ядро ----------
entries = {}   # ka -> dict
order = []

def add(ka, ru, cat, source, pos=''):
    ka = ka.strip()
    if not ka: return
    e = entries.get(ka)
    if e is None:
        e = {'ka': ka, 'tr': translit(ka), 'ru': ru, 'cats': [], 'src': source, 'pos': pos}
        entries[ka] = e
        order.append(ka)
    else:
        if source == 'core' and e['src'] != 'core':
            e['ru'] = ru; e['src'] = 'core'          # ручной перевод приоритетнее
        elif source == e['src'] and len(e['ru']) < 70:
            def norm(x):
                return re.sub(r'[^а-яёa-z ]', '', x.lower()).strip()
            have = [norm(x) for part in e['ru'].split(';') for x in part.split(',') if norm(x)]
            new = []
            for part in ru.split(';'):
                for x in part.split(','):
                    n = norm(x)
                    if not n: continue
                    if any(n in h or h in n for h in have): continue
                    have.append(n); new.append(x.strip())
            if new: e['ru'] = e['ru'] + '; ' + ', '.join(new)
        if not e.get('pos') and pos: e['pos'] = pos
    if cat and cat not in e['cats']:
        if e['src'] == 'core' and source != 'core':
            pass                      # ручная тема точнее: чужую не подмешиваем
        else:
            e['cats'].append(cat)

CORE_POS = {'verbs': 'verb', 'adjectives': 'adj', 'adverbs': 'adv', 'numbers': 'num',
            'pronouns': 'pron', 'phrases': 'phrase', 'greetings': 'phrase',
            'discourse': 'phrase', 'questions': 'pron', 'postpositions': 'prep',
            'character': 'adj', 'colors': 'adj'}
for f in sorted(glob.glob(os.path.join(BASE, 'data/parts/*.json'))):
    for row in json.load(open(f, encoding='utf-8')):
        if len(row) == 4: cat, ka, _tr, ru = row
        else: cat, ka, ru = row
        add(ka, ru, cat, 'core', CORE_POS.get(cat, 'noun'))

core_count = len(entries)

# ---------- 2. Викисловарь ----------
RO_ONLY = re.compile(r"^[a-zăâîșşțţ][a-zăâîșşțţ \-']*$", re.I)
skipped_narrow = 0
for line in open(WIKT, encoding='utf-8'):
    r = json.loads(line)
    ka = r['word'].strip()
    if not RO_ONLY.match(ka) or len(ka) < 2: continue
    if r.get('pos') in ('suffix', 'prefix') or ka.startswith('-') or ka.endswith('-'): continue
    glosses = [clean_gloss(g) for s in r.get('senses', []) for g in (s.get('glosses') or [])]
    glosses = [g for g in glosses if g and not OFFENSIVE.match(g.lower()) and not EXPLICIT.search(g)
                and not HEAVY.search(g)]
    # Побочные значения с пометой сниженного стиля отбрасываем, если у слова есть
    # обычное значение: в учебном словаре они не нужны, а среди них попадается
    # обидная лексика — так в словарь однажды попала унизительная характеристика
    # целого народа, прицепленная вторым значением к нейтральному слову.
    if len(glosses) > 1:
        plain = [g for g in glosses if not SLANG.match(g.lower())]
        if plain: glosses = plain
    if not glosses: continue
    wcats = [c['name'] if isinstance(c, dict) else str(c)
             for c in (r.get('categories') or [])]
    for s in r.get('senses', []):
        wcats += [c['name'] if isinstance(c, dict) else str(c) for c in (s.get('categories') or [])]
    f = wfreq(ka)
    # отсев узкой терминологии у редких слов
    narrow = any(any(n in wc for n in NARROW) for wc in wcats) or bool(NARROW_LABEL.match(glosses[0]))
    if narrow and f < 40:
        skipped_narrow += 1; continue
    # «форма ... слова X» — это словоформа, а не отдельная лексема
    if re.match(r'^(форма|формы|склонение|спряжение)\b', glosses[0].lower()):
        skipped_narrow += 1; continue
    # слово нигде не засвидетельствовано -> скорее опечатка или крайняя редкость
    if not all(x.lower() in attested for x in ka.split()):
        skipped_narrow += 1; continue
    # личные имена и фамилии
    if ka in personal_names or \
       re.match(r'^(мужское|женское)\s+имя|^фамилия', glosses[0].lower()):
        skipped_narrow += 1; continue
    # грубая и обсценная лексика в учебный словарь не идёт
    if re.match(r'^(вульг|груб|бран|обсц|неценз|мат\b|жарг)', glosses[0].lower()):
        skipped_narrow += 1; continue
    # имена собственные и топонимы: держим только заметные
    first = strip_labels(glosses[0])
    is_proper = bool(re.match(r'^[А-ЯЁ][а-яё-]', first)) and not re.match(r'^Я\b', first)
    if is_proper and f < 12:
        skipped_narrow += 1; continue
    # категория
    cat = 'geo' if is_proper else None
    g0 = glosses[0].lower()
    if not cat:
        for pat, c in LABEL_MAP:
            if re.match(pat, g0): cat = c; break
    if not cat:
        for names, c in WCAT_MAP:
            if any(any(n in wc for n in names) for wc in wcats): cat = c; break
    ru_plain = strip_labels('; '.join(glosses[:2])).lower()
    if not cat:
        for c, pat in KEYWORDS:
            if pat.search(ru_plain): cat = c; break
    if not cat and r.get('pos') == 'num':
        cat = 'numbers'
    if not cat and AGENT.match(ru_plain) and r.get('pos') == 'noun':
        cat = 'work'
    if not cat:
        cat = POS_FALLBACK.get(r.get('pos'), 'general')
    ru = strip_labels('; '.join(glosses[:2]))
    ru = re.sub(r'\s*\((?:[^()]{28,})\)', '', ru).strip(' ;,')
    if len(ru) > 80: ru = strip_labels(re.sub(r'\s*\((?:[^()]{28,})\)', '', glosses[0])).strip(' ;,')
    if len(ru) > 80: ru = ru[:77].rsplit(' ', 1)[0] + '…'
    add(ka, ru, cat, 'wikt', r.get('pos', ''))

