# ---------- частоты ----------
freq = {}          # слово -> частота на миллион (максимум по корпусам)
for path in FREQ_FILES:
    raw, total = {}, 0
    for line in open(path, encoding='utf-8'):
        p = line.rstrip('\n').split('\t')
        if len(p) >= 3:
            try: n = int(p[2])
            except ValueError: continue
            raw[p[1]] = raw.get(p[1], 0) + n
            total += n
    for w, n in raw.items():
        ipm = n * 1_000_000 / total
        if ipm > freq.get(w, 0): freq[w] = ipm

def wfreq(w):
    if ' ' in w:
        parts = [freq.get(x, 0) for x in w.split()]
        return round(min(parts)) if parts else 0
    return round(freq.get(w, 0))

